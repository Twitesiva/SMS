-- 2. Define Tables

-- Academic Year
create table if not exists public.academic_year (
  id bigint generated by default as identity primary key,
  academic_year text not null,
  active boolean default true,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Groups (e.g., MPC, BCom)
create table if not exists public.groups (
  group_id bigint generated by default as identity primary key,
  group_name text not null,
  group_code text not null,
  duration_years integer default 3,
  number_semesters integer default 6,
  category text, -- 'UG' or 'PG' etc
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Courses (e.g., BSc MPC, BCom Computers)
create table if not exists public.courses (
  course_id bigint generated by default as identity primary key,
  course_name text not null,
  course_code text not null,
  group_id bigint references public.groups(group_id),
  group_name text, -- De-normalized or used if no FK
  no_of_semesters integer,
