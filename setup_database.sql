-- 3. ENABLE ROW LEVEL SECURITY (RLS) FOR ALL TABLES
-- This prevents '401 Unauthorized' errors by defaulting to restricted, 
-- but we will add open policies for this app.

do $$ 
declare 
  t record;
begin 
  for t in 
    select tablename from pg_tables where schemaname = 'public' 
  loop 
    execute format('alter table public.%I enable row level security;', t.tablename);
    -- Add a generic policy to allow everything (FOR DEVELOPMENT ONLY)
    -- Drop existing if any to avoid conflicts
    execute format('drop policy if exists "Allow All" on public.%I;', t.tablename);
    execute format('create policy "Allow All" on public.%I for all using (true) with check (true);', t.tablename);
  end loop; 
end $$;

-- 4. Fix specific Foreign Keys needed by MainDashboard.jsx
-- The dashboard code explicitly tries to join `groups` via `students_group_id_fkey` 
-- and `courses` via `fk_students_course`. We MUST name them exactly so.

alter table public.students drop constraint if exists students_group_id_fkey;
alter table public.students add constraint students_group_id_fkey 
  foreign key (group_id) references public.groups(group_id);

alter table public.students drop constraint if exists fk_students_course;
alter table public.students add constraint fk_students_course 
  foreign key (course_id) references public.courses(course_id);

